"""Construction of the derived artefacts: derived CSV tables, figure metadata, manifest.

No function launches a training or reads the test set: the inputs are the source
tables and the selection / evaluation JSON files already produced.
All outputs are deterministic (no timestamp, no Git SHA, fixed order).
"""

import hashlib
import json
from importlib import metadata
from pathlib import Path

from src.export import registry
from src.export.csv_io import write_csv
from src.export.layout import Layout

MANIFEST_SCHEMA = "export/1"
KNOWN_LIMITS = (
    "Reproducibility established on a single host and a single BLAS thread, "
    "not across platforms.",
    "Execution logs are not versioned: the absence of any test read before the freeze "
    "rests on the declaration, neutralised by rebuilding the selection from "
    "the validation data alone.",
    "Bands and statistics over 10 or 50 seeds are descriptive, not confidence "
    "confidence (R2).",
    "The final evaluation tables (mlp_2d_final_*, mlp_2d_solver_comparison, "
    "mlp_2d_final_evaluation.json) are not regenerated by the export; their internal consistency and "
    "consistency with the freeze are checked by `main.py verify`.",
)


def sha256_file(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write_text(path, text: str) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return path


def write_json(path, obj) -> Path:
    return write_text(path, json.dumps(obj, sort_keys=True, indent=1, ensure_ascii=False,
                                       allow_nan=False) + "\n")


# --------------------------------------------------------------------------
# Tables
# --------------------------------------------------------------------------
def table_rows(spec: registry.TableSpec, src: registry.Sources) -> list[dict]:
    return src.rows(spec.source) if spec.derive is None else spec.derive(src)


def build_tables(layout: Layout, src: registry.Sources | None = None) -> list[Path]:
    """Write into ``layout.tables`` the CSV of each derived table of the registry."""
    src = src or registry.Sources(layout.tables)
    written = []
    for spec in registry.TABLES:
        rows = table_rows(spec, src)
        if not rows:
            raise ValueError(f"empty table: {spec.stem}")
        if spec.derive is not None:
            written.append(write_csv(layout.tables / f"{spec.stem}.csv", list(rows[0]), rows))
    return written


