def figure_parameters(src: registry.Sources) -> dict:
    """Parameters to quote in the figure captions: read from the source files."""
    from src.data.generator_1d import N_SAMPLES_NOMINAL, SIGMA_NOMINAL
    meta1d = src.json("exploration_1d_metadata.json")
    meta2d = src.json("mlp_2d_metadata.json")
    selection = src.json("mlp_2d_selection.json")
    evaluation = src.json("mlp_2d_final_evaluation.json")
    stat_seeds = meta1d["statistical_seeds"]
    n_runs_sigma = {r["sigma"]: int(r["n_runs"]) for r in src.rows("exploration_sigma_stats")
                    if int(r["degree"]) == 1}
    n_runs_n_samples = {r["n_samples"]: int(r["n_runs"]) for r in src.rows("exploration_n_samples_stats")
                    if int(r["degree"]) == 1}
    nominal_1d = {"illustrative_seed": meta1d["illustration_seed"], "n_samples": N_SAMPLES_NOMINAL,
                  "sigma_train": SIGMA_NOMINAL, "sigma_test": 0.0,
                  "train_domain_range": meta1d["train_domain"],
                  "train_upper_bound": meta1d["train_endpoint"],
                  "n_test": meta1d["test_points"], "degrees": [min(meta1d["degrees"]), max(meta1d["degrees"])]}
    campaign = {"seeds": f"{min(stat_seeds)} to {max(stat_seeds)}", "n_seeds": len(stat_seeds)}
    adam_rows = src.rows("mlp_2d_adam_grid")
    grid_order = [f"lr={float(a):g}, batch={b}" for a, b in meta2d["adam_grid"]]
    by_setting = {(float(r["learning_rate_init"]), int(r["batch_size"])): int(r["n_warnings"])
                  for r in adam_rows}
    adam_warnings = [by_setting[(float(a), int(b))] for a, b in meta2d["adam_grid"]]
    final = selection["final"]["ranking"][0]
    mlp_common = {"monte_carlo_seeds": meta2d["seeds"], "n_realisations_per_configuration": len(meta2d["seeds"]),
                  "h_star": meta2d["h_star"], "final_configuration": final["label"],
                  "figure_network_seed": selection["final"]["figure_network"]["seed"],
                  "n_test": evaluation["n_test"]}
    render = {"render_grid": "200 x 200, step 0.005, bound 1 excluded (np.arange(0, 1, 0.005))",
              "view_3d": {"elev": 30, "azim": -60}}
    return {
        "nominal_1d": {**nominal_1d, "panel_window": [-2.0, 2.0]},
        "campaign_1d": {**nominal_1d, **campaign,
                        "noisy_repetitions": len(stat_seeds)},
        "exploration_n_samples": {"sigma_fixed": SIGMA_NOMINAL, "n_values": meta1d["sizes"],
                              **campaign, "repetitions_per_n": n_runs_n_samples},
        "exploration_sigma": {"n_samples_fixed": N_SAMPLES_NOMINAL, "sigma_values": meta1d["sigmas"], **campaign,
                              "repetitions_per_sigma": n_runs_sigma,
                              "note": "sigma = 0: a single realisation (the draws would be identical)"},
        "exploration_extrapolation": {"extended_domain": meta1d["extended_domain"],
                                      "render_points": meta1d["extended_points"], **campaign,
                                      "selection": meta1d["selection"]},
        "mlp_campaigns": {**mlp_common,
                          "adam_grid_order": grid_order,
                          "adam_warnings_in_grid_order": adam_warnings,
                          "adam_budget": meta2d["adam_protocol"], "lbfgs_budget": meta2d["lbfgs_budget"]},
        "mlp_model": {**mlp_common, **render},
    }


